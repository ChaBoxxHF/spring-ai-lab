CREATE TABLE clients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name  VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    CONSTRAINT uk_clients_email UNIQUE (email),
    CONSTRAINT ck_clients_email_lower_case CHECK (email = LOWER(email))
);

CREATE TABLE products (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(255)   NOT NULL,
    name      VARCHAR(255)   NOT NULL,
    price     NUMERIC(19, 2) NOT NULL,
    active    BOOLEAN        NOT NULL,
    CONSTRAINT uk_products_reference UNIQUE (reference),
    CONSTRAINT ck_products_price_positive CHECK (price > 0)
);

CREATE TABLE orders (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT      NOT NULL,
    status    VARCHAR(20) NOT NULL,
    version   BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT fk_orders_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED'))
);

CREATE TABLE order_lines (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    product_id BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_order_lines_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_lines_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_orders_client_id ON orders (client_id);
CREATE INDEX idx_order_lines_order_id ON order_lines (order_id);
